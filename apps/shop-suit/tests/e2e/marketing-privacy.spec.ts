import { test, expect } from '@playwright/test'
import type { Page, BrowserContext } from '@playwright/test'
import { catalog } from './marketing-privacy-fixture.mjs'
const origin = 'https://shop.building-suit.com'
const dispatched = new WeakMap<BrowserContext, unknown[][]>()
async function fixture(context: BrowserContext, port = 4337, host = origin) {
  const requests: string[] = []
  const recorded: unknown[][] = []
  dispatched.set(context, recorded)
  await context.exposeBinding('__recordSyntheticAnalytics', (_source, event: unknown[]) => { recorded.push(event) })
  await context.route(`${host}/**`, async route => {
    const url = new URL(route.request().url())
    const response = await route.fetch({ url: `http://127.0.0.1:${port}${url.pathname}${url.search}`, headers: { ...route.request().headers(), host: new URL(host).host, 'x-forwarded-proto': 'https' } })
    await route.fulfill({ response })
  })
  await context.route(/https:\/\/[^/]*(googletagmanager|google-analytics)\.com\//, async route => {
    requests.push(route.request().url())
    await route.fulfill({ contentType: 'text/javascript', body: `/* Synthetic provider stub, no Google collection requests. */
      const originalPush = dataLayer.push.bind(dataLayer);
      dataLayer.push = function(args) { parent.__recordSyntheticAnalytics(JSON.parse(JSON.stringify(Array.from(args)))); return originalPush(args) };` })
  })
  await context.route('http://127.0.0.1:46423/**', route => route.fulfill({ json: catalog, headers: { 'access-control-allow-origin': '*' } }))
  await context.addCookies([{ name: 'building-suit-locale', value: 'en', url: host }])
  return requests
}
async function events(page: Page) {
  return page.evaluate(() => {
    const frame = document.querySelector<HTMLIFrameElement>('iframe[title="Optional analytics"]')
    return ((frame?.contentWindow as Window & { dataLayer?: IArguments[] })?.dataLayer || []).map(args => Array.from(args))
  })
}
async function accept(page: Page) {
  await page.getByRole('button', { name: 'Accept optional', exact: true }).click()
  await expect(page.locator('iframe[title="Optional analytics"]')).toHaveCount(1)
  await expect.poll(async () => (await events(page)).filter(event => event[0] === 'event').length).toBeGreaterThan(0)
}
test('no pre-consent network, equally usable choices, safe URLs, reload, withdrawal and cookies', async ({ page, context }) => {
  const requests = await fixture(context)
  await page.goto(origin + '/?email=private@example.test#private')
  await expect(page.getByRole('button', { name: 'Reject optional', exact: true })).toBeVisible()
  expect(requests).toEqual([])
  await page.screenshot({ path: '.local/seo-privacy-evidence/consent-en.png' })
  expect(await page.locator('iframe').count()).toBe(0)
  await accept(page)
  expect(requests).toHaveLength(1)
  const captured = JSON.stringify(await events(page))
  expect(captured).not.toMatch(/private@example|#private|\?email/)
  expect(captured).toContain('"page_location":"https://shop.building-suit.com/"')
  expect(captured).toContain('"allow_google_signals":false')
  expect(captured).toContain('"ad_storage":"denied"')
  await page.reload()
  await expect.poll(() => requests.length).toBe(2)
  await context.addCookies([{ name: '_ga', value: 'synthetic', url: origin }, { name: '_ga_TESTONLY', value: 'synthetic', url: origin }, { name: 'bs-shop-production-auth-token', value: 'synthetic-not-a-session', url: origin }])
  await page.getByRole('button', { name: 'Privacy settings', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Reject optional' }).click()
  await expect(page.locator('iframe[title="Optional analytics"]')).toHaveCount(0)
  const cookies = await context.cookies()
  expect(cookies.some(cookie => cookie.name.startsWith('_ga'))).toBe(false)
  expect(cookies.some(cookie => cookie.name === 'bs-shop-production-auth-token')).toBe(true)
  await page.reload()
  expect(requests).toHaveLength(2)
  await expect(page.getByRole('region', { name: 'Privacy choices' })).toHaveCount(0)
  const choice = await page.evaluate(() => JSON.parse(localStorage.getItem('bs-shop.privacy') || '{}'))
  expect(choice.analytics).toBe(false)
})
