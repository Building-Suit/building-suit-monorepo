import { test, expect, type Page } from '@playwright/test'
const fixture = 'http://127.0.0.1:4338/__fixture'
const practiceId = '73000000-0000-0000-0000-000000000001'
function location(n: number, name: string, timezone: string) { return { id: `75000000-0000-0000-0000-${String(n).padStart(12, '0')}`, practice_id: practiceId, name, timezone, version: 1, contact_phone: `Synthetic phone ${n}`, contact_address: `Synthetic address ${n}`, archived_at: null } }
test.beforeEach(async ({ request, page }) => {
  await request.post(fixture, { data: { reset: true } })
  await request.post(fixture, { data: { profile: { display_name: 'Synthetic owner', professional_verification: 'unverified' }, practice: { id: practiceId, name: 'Synthetic practice', version: 1 }, locations: [location(1, 'Clinic A', 'Africa/Cairo'), location(2, 'Clinic B', 'Europe/London')] } })
  await page.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
})
async function choose(page: Page, ar: boolean, name: string) {
  await page.getByRole('combobox', { name: ar ? 'الممارسة والموقع' : 'Practice and location', exact: true }).click()
  await page.getByRole('option', { name: new RegExp(`Synthetic owner · ${name}`) }).click()
}
for (const ar of [false, true]) test(`DOS-M1-008 ${ar ? 'AR mobile' : 'EN desktop'} protocol fixture: explicit context, location writes and retained archive history`, async ({ page, context, request }) => {
  await page.setViewportSize({ width: ar ? 390 : 1280, height: 1000 })
  await context.addCookies([{ name: 'building-suit-locale', value: ar ? 'ar' : 'en', url: 'http://127.0.0.1:4337' }])
  await page.goto('/account')
  await page.getByLabel(ar ? /^البريد الإلكتروني/ : /^Email/).fill('synthetic@example.test')
  await page.getByLabel(ar ? /^كلمة المرور/ : /^Password/).fill('synthetic-password-only')
  await page.getByRole('button', { name: ar ? 'تسجيل الدخول' : 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  await page.getByRole('link', { name: ar ? 'مواقع العمل' : 'Working locations', exact: true }).click()
  await choose(page, ar, 'Clinic A')
  await expect(page.getByRole('row', { name: /Clinic A/ })).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: 'Clinic A' })).toBeVisible()
  await page.getByRole('button', { name: ar ? 'إضافة موقع' : 'Add location', exact: true }).click()
  const editor = page.getByRole('dialog', { name: ar ? 'إضافة موقع' : 'Add location', exact: true })
  await editor.getByLabel(ar ? /^اسم الموقع/ : /^Location name/).fill('Clinic C')
  await editor.getByLabel(ar ? /^المنطقة الزمنية/ : /^IANA timezone/).fill('Asia/Dubai')
  await editor.getByLabel(ar ? /^هاتف التواصل/ : /^Contact phone/).fill('Synthetic C phone')
  await editor.getByRole('button', { name: ar ? 'حفظ الموقع' : 'Save location', exact: true }).click()
  await expect(editor).toBeHidden()
  await expect(page.getByRole('row', { name: /Clinic C/ })).toBeVisible()
  await page.getByRole('searchbox', { name: ar ? 'البحث في المواقع' : 'Search locations', exact: true }).fill('Clinic B')
  await expect(page.getByRole('row', { name: /Clinic A/ })).toHaveCount(0)
  await choose(page, ar, 'Clinic C')
  await expect(page.getByRole('searchbox', { name: ar ? 'البحث في المواقع' : 'Search locations', exact: true })).toHaveValue('')
  await expect(page.getByRole('status').filter({ hasText: 'Clinic C' })).toBeVisible()
  const row = page.getByRole('row', { name: /Clinic C/ })
  await row.getByRole('button', { name: ar ? 'تعديل الموقع' : 'Edit location', exact: true }).click()
  const edit = page.getByRole('dialog', { name: ar ? 'تعديل الموقع' : 'Edit location', exact: true })
  await edit.getByLabel(ar ? /^المنطقة الزمنية/ : /^IANA timezone/).fill('Etc/UTC')
  await edit.getByRole('button', { name: ar ? 'حفظ الموقع' : 'Save location', exact: true }).click()
  await expect(edit).toBeHidden()
  await expect(page.getByRole('status').filter({ hasText: 'Clinic C' })).toContainText('Etc/UTC')
  await page.getByRole('row', { name: /Clinic C/ }).getByRole('button', { name: ar ? 'أرشفة الموقع' : 'Archive location', exact: true }).click()
  const archive = page.getByRole('dialog', { name: ar ? 'أرشفة الموقع: Clinic C' : 'Archive location: Clinic C', exact: true })
  await archive.getByRole('button', { name: ar ? 'أرشفة الموقع' : 'Archive location', exact: true }).click()
  await expect(archive).toBeHidden()
  await choose(page, ar, 'Clinic A')
  await expect(page.getByRole('row', { name: /Clinic C/ })).toContainText(ar ? 'مؤرشف' : 'Archived')
  await expect(page.getByRole('row', { name: /Clinic C/ }).getByRole('button')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  const state = await (await request.get(fixture)).json()
  expect(state.locations.length).toBe(3)
  expect(state.practice.id).toBe(practiceId)
  expect(state.locations.find((item: { name: string }) => item.name === 'Clinic C').archived_at).not.toBeNull()
})

test('DOS-M1-008 protocol fixture: an owner with every location archived retains history and can create a new working location', async ({ page, request }) => {
  await request.post(fixture, { data: { locations: [{ ...location(1, 'Archived clinic', 'Africa/Cairo'), archived_at: '2026-10-16T00:00:00Z', version: 2 }] } })
  await page.goto('/account')
  await page.getByLabel(/^Email/).fill('synthetic@example.test')
  await page.getByLabel(/^Password/).fill('synthetic-password-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  await page.getByRole('link', { name: 'Working locations', exact: true }).click()
  await expect(page.getByRole('row', { name: /Archived clinic/ })).toContainText('Archived')
  await page.getByRole('button', { name: 'Add location', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Add location', exact: true })
  await dialog.getByLabel(/^Location name/).fill('New working clinic')
  await dialog.getByLabel(/^IANA timezone/).fill('Europe/London')
  await dialog.getByRole('button', { name: 'Save location', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('row', { name: /Archived clinic/ })).toBeVisible()
  await expect(page.getByRole('row', { name: /New working clinic/ })).toBeVisible()
  const state = await (await request.get(fixture)).json()
  expect(state.locations.length).toBe(2)
  expect(state.practice.id).toBe(practiceId)
})
