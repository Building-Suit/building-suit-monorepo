import { test, expect, type Page, type BrowserContext } from '@playwright/test'
const fixture = 'http://127.0.0.1:4338/__fixture'
test.beforeEach(async ({ request }) => { await request.post(fixture, { data: { reset: true, completeDelayMs: 250 } }); await request.post(fixture, { data: { completeDelayMs: 250 } }) })
async function prepare(context: BrowserContext, ar: boolean) {
  await context.addCookies([{ name: 'building-suit-locale', value: ar ? 'ar' : 'en', url: 'http://127.0.0.1:4337' }])
  await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
}
async function signIn(page: Page, ar = false) {
  await page.goto('/sign-in')
  await page.getByLabel(ar ? /^البريد الإلكتروني/ : /^Email/).fill('synthetic@example.test')
  await page.getByLabel(ar ? /^كلمة المرور/ : /^Password/).fill('synthetic-password-only')
  await page.getByRole('button', { name: ar ? 'تسجيل الدخول' : 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
}
for (const ar of [false, true]) test(`DOS-M1-007 ${ar ? 'AR mobile' : 'EN desktop'} protocol fixture: resume draft, onboard alone and maintain profile`, async ({ page, context, browser, request }) => {
  await prepare(context, ar)
  await page.setViewportSize({ width: ar ? 390 : 1280, height: 1000 })
  await signIn(page, ar)
  await page.getByRole('link', { name: ar ? 'إكمال إعداد الممارسة' : 'Complete practice setup', exact: true }).click()
  await page.getByLabel(ar ? /^الاسم المعروض للطبيب/ : /^Doctor display name/).fill('Synthetic owner')
  await expect(page.locator('input[type="password"], input[type="email"], input[type="tel"]')).toHaveCount(0)
  await page.getByRole('button', { name: ar ? 'حفظ المسودة' : 'Save draft', exact: true }).click()
  await expect(page.getByText(ar ? 'حُفظت المسودة ويمكن استئنافها من جلسة أخرى.' : 'Draft saved. Resume it from another session.', { exact: true })).toBeVisible()
  const resumed = await browser.newContext({ baseURL: 'http://127.0.0.1:4337', viewport: { width: ar ? 390 : 1280, height: 1000 } })
  try {
    await prepare(resumed, ar)
    const second = await resumed.newPage()
    await signIn(second, ar)
    await second.goto('/onboarding')
    await expect(second.getByLabel(ar ? /^الاسم المعروض للطبيب/ : /^Doctor display name/)).toHaveValue('Synthetic owner')
    await second.getByLabel(ar ? /^اسم الممارسة/ : /^Practice name/).fill('Synthetic practice')
    await second.getByLabel(ar ? /^اسم الموقع/ : /^Location name/).fill('Synthetic first location')
    await second.getByLabel(ar ? /^المنطقة الزمنية/ : /^IANA timezone/).fill('Africa/Cairo')
    await second.getByRole('button', { name: ar ? 'إنشاء الممارسة' : 'Create practice', exact: true }).click({ clickCount: 2 })
    await expect(second).toHaveURL(/\/workspace$/)
    await expect(second.getByRole('heading', { level: 1, name: ar ? 'مساحة الممارسة' : 'Practice workspace' })).toBeVisible()
    await expect(second.getByRole('heading', { name: 'Synthetic practice', exact: true })).toBeVisible()
    await expect(second.getByText(ar ? 'المؤهلات المهنية غير متحقق منها' : 'Professional credentials unverified', { exact: true })).toBeVisible()
    await expect(second.getByText('Africa/Cairo', { exact: true })).toBeVisible()
    expect(await second.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    await expect(second.getByRole('status').filter({ hasText: 'Synthetic practice · Synthetic first location · Africa/Cairo' })).toBeVisible()
    await expect(second.getByRole('main')).toHaveCount(1)
    expect((await (await request.get(fixture)).json()).completeCalls).toBe(1)
    await second.getByRole('link', { name: ar ? 'تعديل ملف الممارسة' : 'Edit practice profile', exact: true }).last().click()
    await second.getByLabel(ar ? /^اسم الممارسة/ : /^Practice name/).fill('Updated synthetic practice')
    await second.getByRole('button', { name: ar ? 'حفظ الملف' : 'Save profile', exact: true }).click()
    await expect(second).toHaveURL(/\/workspace$/)
    await expect(second.getByRole('heading', { name: 'Updated synthetic practice', exact: true })).toBeVisible()
    const state = await (await request.get(fixture)).json()
    expect(state.profileCalls).toBe(1)
    expect(state.profile.professional_verification).toBe('unverified')
    expect(state.location.name).toBe('Synthetic first location')
  } finally { await resumed.close() }
})
test('DOS-M1-007 protocol fixture: delegated membership cannot expose owner forms or writes', async ({ page, context, request }) => {
  await prepare(context, false)
  await request.post(fixture, { data: { enrollment: 'delegated-only' } })
  await signIn(page)
  await page.goto('/onboarding')
  await expect(page.getByText('Owner setup unavailable', { exact: true })).toBeVisible()
  await expect(page.locator('input')).toHaveCount(0)
  const state = await (await request.get(fixture)).json()
  expect(state.completeCalls).toBe(0)
  expect(state.calls.some((value: string) => value.includes('doctor_save_onboarding_draft'))).toBe(false)
})
