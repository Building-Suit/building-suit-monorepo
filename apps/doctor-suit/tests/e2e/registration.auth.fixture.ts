import { test, expect, type Page } from '@playwright/test'
const fixture = 'http://127.0.0.1:4338/__fixture'
test.beforeEach(async ({ request, page }, info) => {
  await request.post(fixture, { data: { reset: true } })
  const seed = Array.from(info.testId).reduce((n, character) => (n * 31 + character.charCodeAt(0)) >>> 0, 1)
  await page.setExtraHTTPHeaders({ 'x-forwarded-for': `127.${seed >>> 16 & 255}.${seed >>> 8 & 255}.${seed & 255}` })
  await page.route('**/*', route => ['127.0.0.1','localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
})
