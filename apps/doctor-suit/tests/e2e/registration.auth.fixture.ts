for (const ar of [false, true]) test(`auth links retain the document and navigation history ${ar ? 'AR mobile light' : 'EN desktop dark'}`, async ({ page, context }) => {
  await page.setViewportSize({ width: ar ? 390 : 1280, height: 900 })
  await context.addCookies([{ name: 'building-suit-locale', value: ar ? 'ar' : 'en', url: 'http://127.0.0.1:4337' }])
  await page.addInitScript(theme => localStorage.setItem('building-suit.theme', theme), ar ? 'light' : 'dark')
  await page.goto('/sign-in')
  const sentinel = await page.evaluate(() => { const value = crypto.randomUUID(); (window as Window & { doctorDocument?: string }).doctorDocument = value; return value })
  let documents = 0; page.on('request', request => { if (request.isNavigationRequest() && request.frame() === page.mainFrame()) documents++ })
  await page.getByRole('link', { name: ar ? 'إنشاء حساب تجريبي' : 'Create synthetic account', exact: true }).click()
  await expect(page.getByLabel(ar ? /^الاسم المعروض/ : /^Display name/)).toBeVisible()
  await page.getByRole('link', { name: ar ? 'تسجيل الدخول' : 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await expect(page.locator('input[autocomplete="new-password"]')).toHaveCount(0)
  const signIn = page.locator('form[data-client-ready="true"]').filter({ has: page.getByRole('heading', { name: ar ? 'تسجيل الدخول' : 'Sign in', exact: true }) })
  await expect(signIn).toHaveCount(1)
  await signIn.getByLabel(ar ? /^البريد الإلكتروني/ : /^Email/).fill('synthetic@example.test')
  await signIn.locator('button[type="submit"]').click()
  await expect(signIn.locator('input[autocomplete="current-password"]')).toBeFocused()
  await page.getByRole('link', { name: ar ? 'استعادة كلمة المرور' : 'Recover password', exact: true }).click()
  await expect(page).toHaveURL(/\/recover$/)
  await expect(signIn).toHaveCount(0)
  await expect(page.getByLabel(ar ? /^البريد الإلكتروني/ : /^Email/)).toBeVisible()
  await page.goBack(); await expect(page).toHaveURL(/\/sign-in$/); await expect(signIn).toHaveCount(1)
  await page.goForward(); await expect(page).toHaveURL(/\/recover$/); await expect(signIn).toHaveCount(0)
  expect(await page.evaluate(() => (window as Window & { doctorDocument?: string }).doctorDocument)).toBe(sentinel); expect(documents).toBe(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
test('unavailable lookup and rate limits fail closed with a boolean-only server response', async ({ request }) => {
  const headers = { 'x-forwarded-for': '127.243.24.17' }, url = 'http://127.0.0.1:4337/api/auth/email-step'
  for (let index = 0; index < 4; index++) {
    const response = await request.post(url, { headers, data: { email: 'synthetic@example.test', intent: 'sign-in' } })
    expect(response.status()).toBe(200); expect(await response.json()).toEqual({ canContinue: true }); expect(response.headers()['cache-control']).toBe('no-store')
  }
  expect((await request.post(url, { headers, data: { email: 'synthetic@example.test', intent: 'sign-in' } })).status()).toBe(429)
  expect((await request.post(url, { data: { email: 'bad', intent: 'sign-in' } })).status()).toBe(422)
  await request.post(fixture, { data: { emailLookupMalformed: true } })
  const unavailable = await request.post(url, { headers: { 'x-forwarded-for': '127.243.24.18' }, data: { email: 'synthetic@example.test', intent: 'sign-in' } })
  expect(unavailable.status()).toBe(503)
  expect(JSON.stringify(await unavailable.json())).not.toContain('SYNTHETIC_INVALID_RESPONSE')
})
