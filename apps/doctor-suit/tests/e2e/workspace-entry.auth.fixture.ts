import { doctorPasswordStep } from '../helpers/password-step.mjs'
import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
const fixture = 'http://127.0.0.1:4338/__fixture'
test('changing language through settings survives setup, account return and reload', async ({ page, request, context }) => {
  await request.post(fixture, { data: { reset: true } })
  await context.addCookies([{ name: 'building-suit-locale', value: 'en', url: 'http://127.0.0.1:4337' }])
  await page.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
  await page.goto('/sign-in')
  await page.getByRole('button', { name: 'Language · Theme', exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'العربية', exact: true }).click()
  await page.getByLabel(/^البريد الإلكتروني/).fill('synthetic@example.test')
  await doctorPasswordStep(page)
  await page.getByLabel(/^كلمة المرور/).fill('synthetic-password-only')
  await page.getByRole('button', { name: 'تسجيل الدخول', exact: true }).click()
  await expect(page).toHaveURL(/\/onboarding$/)
  await page.getByRole('link', { name: 'العودة إلى الحساب', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  await expect(page.getByRole('heading', { name: 'الحساب التجريبي', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'الحساب التجريبي', exact: true })).toBeVisible()
  expect((await context.cookies()).find(cookie => cookie.name === 'building-suit-locale')?.value).toBe('ar')
})
test('canonical Doctor artwork is served byte for byte with discovered SVG favicon', async ({ page, request }) => {
  for (const kind of ['mark', 'wordmark']) for (const tone of ['light', 'dark']) {
    const filename = `doctor-suit-${kind}-${tone}.svg`
    const response = await request.get(`/brand/${filename}`)
    expect(response.status()).toBe(200)
    expect(response.headers()['content-type']).toContain('image/svg+xml')
    expect(await response.body()).toEqual(await readFile(new URL(`../../../../packages/brand/assets/${filename}`, import.meta.url)))
  }
  await page.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
  await page.goto('/')
  await expect(page.locator('link[rel="icon"][href="/brand/doctor-suit-mark-light.svg"]')).toHaveCount(1)
  const logos = page.locator('img[src^="/brand/doctor-suit-"]:visible')
  expect(await logos.count()).toBeGreaterThan(0)
  for (const logo of await logos.all()) expect(await logo.evaluate((node: HTMLImageElement) => node.complete && node.naturalWidth > 0)).toBe(true)
})
for (const ar of [false, true]) test(`linear setup, dashboard return and language retention ${ar ? 'AR mobile light' : 'EN desktop dark'}`, async ({ page, request, context }, info) => {
  await request.post(fixture, { data: { reset: true } })
  await page.setExtraHTTPHeaders({ 'x-forwarded-for': `127.245.1.${info.parallelIndex + (ar ? 31 : 30)}` })
  await context.addCookies([{ name: 'building-suit-locale', value: ar ? 'ar' : 'en', url: 'http://127.0.0.1:4337' }])
  await page.setViewportSize({ width: ar ? 390 : 1280, height: 900 })
  await page.addInitScript(theme => localStorage.setItem('building-suit.theme', theme), ar ? 'light' : 'dark')
  await page.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
  await page.goto('/sign-in')
  const settings = page.getByRole('button', { name: ar ? 'اللغة · المظهر' : 'Language · Theme', exact: true })
  await settings.click()
  await expect(page.getByRole('menuitemradio', { name: 'English', exact: true })).toBeVisible()
  await expect(page.getByRole('menuitemradio', { name: 'العربية', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByLabel(ar ? /^البريد الإلكتروني/ : /^Email/).fill('synthetic@example.test')
  await doctorPasswordStep(page)
  await page.getByLabel(ar ? /^كلمة المرور/ : /^Password/).fill('synthetic-password-only')
  await page.getByRole('button', { name: ar ? 'تسجيل الدخول' : 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/onboarding$/)
  await page.getByLabel(ar ? /^الاسم المعروض للطبيب/ : /^Doctor display name/).fill('Synthetic doctor')
  await page.getByRole('button', { name: ar ? 'متابعة' : 'Continue', exact: true }).click()
  await page.getByLabel(ar ? /^اسم الممارسة/ : /^Practice name/).fill('Synthetic practice')
  await page.getByLabel(ar ? /^اسم الموقع/ : /^Location name/).fill('Synthetic clinic')
  await page.getByRole('combobox', { name: ar ? 'المنطقة الزمنية' : 'Timezone', exact: true }).click()
  await page.getByRole('option', { name: 'Africa/Cairo', exact: true }).click()
  // Account return preserves language and the server-backed resumable draft.
  await page.getByRole('button', { name: ar ? 'حفظ المسودة' : 'Save draft', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: ar ? 'حُفظت المسودة' : 'Draft saved' })).toBeVisible()
  await page.getByRole('link', { name: ar ? 'العودة إلى الحساب' : 'Back to account', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  await expect(page.locator('html')).toHaveAttribute('lang', ar ? /^ar/ : /^en/)
  await page.getByRole('link', { name: ar ? 'إكمال إعداد الممارسة' : 'Complete practice setup', exact: true }).first().click()
  await expect(page).toHaveURL(/\/onboarding$/)
  await page.getByRole('button', { name: ar ? 'متابعة' : 'Continue', exact: true }).click()
  await expect(page.getByLabel(ar ? /^اسم الممارسة/ : /^Practice name/)).toHaveValue('Synthetic practice')
  await page.getByRole('button', { name: ar ? 'إنشاء الممارسة وفتح لوحة التحكم' : 'Create practice and open dashboard', exact: true }).click()
  await expect(page).toHaveURL(/\/workspace$/)
  await expect(page.getByRole('heading', { name: ar ? 'لوحة التحكم' : 'Dashboard', exact: true })).toBeVisible()
  if (!ar) await expect(page.getByRole('button', { name: 'Language: English', exact: true })).toHaveText('English')
  await page.goto('/account')
  await page.getByRole('link', { name: ar ? 'لوحة التحكم' : 'Dashboard', exact: true }).click()
  await expect(page).toHaveURL(/\/workspace$/)
  await page.reload()
  await expect(page.getByRole('heading', { name: ar ? 'لوحة التحكم' : 'Dashboard', exact: true })).toBeVisible()
  await page.goto('/')
  if (ar) await page.getByRole('button', { name: 'فتح القائمة', exact: true }).click()
  await page.getByRole('link', { name: ar ? 'مساحة العمل' : 'Open workspace', exact: true }).click()
  await expect(page).toHaveURL(/\/workspace$/)
  await expect(page.getByRole('heading', { name: ar ? 'لوحة التحكم' : 'Dashboard', exact: true })).toBeVisible()
  expect((await (await request.get(fixture)).json()).completeCalls).toBe(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
