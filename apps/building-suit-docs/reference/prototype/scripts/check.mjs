ok("button primitive matches design-system reference", styles.includes("padding: var(--bs-space-3) var(--bs-space-5)") && styles.includes("box-shadow: var(--bs-elevation-1)") && styles.includes("font-weight: var(--bs-weight-semibold)"));
ok("input primitive matches design-system reference except floating label", styles.includes("border: 1.5px solid var(--bs-border)") && styles.includes("box-shadow: 0 0 0 3px rgba(216, 155, 66, 0.15)") && styles.includes("font-size: var(--bs-type-body-m-size)"));
ok("semantic colors are not decorative auth hero washes", !/rgba\(46,\s*158,\s*107|rgba\(47,\s*119,\s*201|rgba\(209,\s*75,\s*75/.test(styles));
ok("RTL keeps brand lockup LTR", styles.includes("[dir=\"rtl\"] .brand-mark"));
