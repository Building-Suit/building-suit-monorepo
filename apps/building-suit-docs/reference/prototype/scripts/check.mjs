const failed = checks.filter((check) => !check.condition);
for (const check of checks) {
  console.log(`${check.condition ? "PASS" : "FAIL"}  ${check.name}`);
}

if (failed.length) {
  console.error(`\n${failed.length} failed, ${checks.length - failed.length} passed.`);
  process.exit(1);
}

console.log(`\n${checks.length} passed, 0 failed.`);
