ok("brand input radius token is preserved", styles.includes("--bs-radius-input: 12px") && styles.includes("border-radius: var(--bs-radius-input)"));
ok("spacing uses the 8px token scale", offScaleSpacing.length === 0);
ok("auth form gap uses token scale", styles.includes(".auth-form {\n  display: grid;\n  gap: 16px;") && !styles.includes("gap: 15px"));
ok("buttons use 12px brand radius, not pill radius", buttonRadiusRules.every((rule) => rule.test(styles)));
ok("reference design-system tokens are present", styles.includes("--bs-font-latin") && styles.includes("--bs-button-height: 48px") && styles.includes("--bs-motion-quick: 120ms ease"));
ok("focus ring uses Premium Gold, not Gold 700", styles.includes("--bs-focus-ring: var(--bs-premium-gold)") && !/focus-ring:\s*var\(--bs-gold-700\)|focus-ring:\s*#a86c1c/i.test(styles));
