ok("React is not installed", !JSON.stringify(pkg).toLowerCase().includes("react"));
ok("auth-html-css folder removed", !existsSync(join(root, "auth-html-css")));
ok("old Pug folder removed", !existsSync(join(root, "pug")));
ok("old source-css folder removed", !existsSync(join(root, "src/css")));
ok("old standalone dist is regenerated by Vite", existsSync(join(root, "dist/index.html")));
ok("logo assets live in public", existsSync(join(root, "public/assets/logos/building-suit-logo-light.png")));
ok("shared auth screen component is used", app.includes("<AuthScreen"));
ok("shared floating field component is used", app.includes("<FloatingField"));
ok("language and color mode switchers are in Vue", app.includes("<ViewSwitchers"));
ok("every auth screen uses shared switchers", (app.match(/<ViewSwitchers/g) || []).length === 7);
ok("actual Google mark component is used", app.includes("<GoogleMark"));
ok("forgot password text preserved", app.includes("forgot password?"));
ok("brand lockup uses logo-adjacent uilding Suit", app.includes("uilding Suit"));
ok("brand lockup text uses Display token and end alignment", /\.brand-mark\s*\{[\s\S]*?align-items:\s*end;[\s\S]*?font-size:\s*var\(--bs-type-display-size\);[\s\S]*?line-height:\s*var\(--bs-type-display-lh\);[\s\S]*?font-weight:\s*var\(--bs-weight-extrabold\);/.test(styles));
ok("outlined floating label behavior exists", styles.includes(".floating-field:focus-within .field-label"));
