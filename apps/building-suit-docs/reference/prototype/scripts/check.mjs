import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const checks = [];

function ok(name, condition) {
  checks.push({ name, condition: Boolean(condition) });
}

function read(path) {
  return readFileSync(join(root, path), "utf8");
}

function walk(dir, out = []) {
  for (const item of readdirSync(join(root, dir))) {
    if (["node_modules", ".vite"].includes(item)) continue;
    const rel = join(dir, item);
    const abs = join(root, rel);
    const stat = statSync(abs);
    if (stat.isDirectory()) walk(rel, out);
    else out.push(rel);
  }
  return out;
}

const pkg = JSON.parse(read("package.json"));
const app = read("src/App.js");
const authIcon = read("src/components/AuthIcon.js");
const styles = read("src/styles.css");
const files = walk(".");
const textFiles = files.filter(
  (file) => /\.(js|css|html|json|mjs)$/.test(file) && file !== "scripts/check.mjs"
);
const combined = textFiles.map((file) => read(file)).join("\n");
const spacingScale = new Set(["0", "4", "8", "12", "16", "24", "32", "48", "64", "96"]);
const spacingMatches = [...styles.matchAll(/^\s*(gap|padding(?:-[a-z]+)*|margin(?:-[a-z]+)*):\s*([^;]+);/gm)];
const offScaleSpacing = spacingMatches.filter(([, , value]) => {
  const pxValues = [...value.matchAll(/-?(\d+)px/g)].map((match) => match[1]);
  return pxValues.some((size) => !spacingScale.has(size));
});
const buttonRadiusRules = [
  /\.auth-switchers button\s*\{[\s\S]*?border-radius:\s*var\(--bs-radius-button\);/,
  /\.button\s*\{[\s\S]*?border-radius:\s*var\(--bs-radius-button\);/,
  /\.icon-button\s*\{[\s\S]*?border-radius:\s*var\(--bs-radius-button\);/,
  /\.field-icon-button\s*\{[\s\S]*?border-radius:\s*var\(--bs-radius-button\);/
];

