// Generate the focused PostgREST contract from the migrated PostgreSQL catalog.
// psql -XAtf scripts/ap-contract-catalog.sql ... | node scripts/generate-ap-contracts.mjs
import { readFileSync, writeFileSync } from 'node:fs'
const rows = JSON.parse(readFileSync(0, 'utf8'))
if (!Array.isArray(rows) || rows.length !== 6) throw new Error('Expected all six migrated AP RPCs')
const types = { uuid: 'string', text: 'string', date: 'string', character: 'string', jsonb: 'Json', bigint: 'string | number' }
function fields(value, args = false) {
  return value.split(', ').map(field => {
    const [name, type] = field.split(' ')
    if (!types[type]) throw new Error(`Unsupported catalog type: ${type}`)
    const optional = args && field.includes(' DEFAULT ')
    return `        ${name}${optional ? '?' : ''}: ${types[type]}${optional ? ' | null' : ''}`
  }).join('\n')
}
const functions = rows.sort((a, b) => a.proname.localeCompare(b.proname)).map(row => {
  const result = row.result.startsWith('TABLE(')
    ? `{\n${fields(row.result.slice(6, -1))}\n      }[]` : types[row.result]
  if (!result) throw new Error(`Unsupported result: ${row.result}`)
  return `    ${row.proname}: {\n      Args: {\n${fields(row.args, true)}\n      }\n      Returns: ${result}\n    }`
}).join('\n')
writeFileSync(new URL('../types/ap-rpc.types.ts', import.meta.url), `// Generated by scripts/generate-ap-contracts.mjs from the migrated PostgreSQL catalog.\n// Bigint accepts decimal strings to preserve exact PostgREST transport. Do not edit.\nimport type { Json } from './database.types'\n\nexport type ApRpcDatabase = {\n  public: {\n    Tables: Record<string, never>\n    Views: Record<string, never>\n    Functions: {\n${functions}\n    }\n    Enums: Record<string, never>\n    CompositeTypes: Record<string, never>\n  }\n}\n`)
