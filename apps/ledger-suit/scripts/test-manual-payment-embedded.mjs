if (process.argv.includes('--generate-contract')) {
  const models = { manual_payment_requests: 'ManualPaymentRequest', manual_payment_evidence: 'ManualPaymentEvidence', manual_payment_history: 'ManualPaymentHistory' }
  const tsType = (name) => {
    if (name === 'billing_interval') return "'monthly' | 'yearly'"
    if (['int8', 'int4', 'int2', 'numeric'].includes(name)) return 'number'
    if (name === 'bool') return 'boolean'
    if (['uuid', 'text', 'bpchar', 'timestamptz'].includes(name)) return 'string'
    throw new Error(`Unmapped catalog type: ${name}`)
  }
  let output = '// Generated by scripts/test-manual-payment-embedded.mjs --generate-contract.\n// Source: migrated PostgreSQL catalog. Do not edit.\n\n'
  for (const [table, model] of Object.entries(models)) {
    const { rows } = await db.query(`select a.attname,t.typname,a.attnotnull from pg_attribute a join pg_type t on t.oid=a.atttypid where a.attrelid=$1::regclass and a.attnum>0 and not a.attisdropped order by a.attnum`, [`public.${table}`])
    output += `export type ${model} = {\n${rows.map(row => `  ${row.attname}: ${tsType(row.typname)}${row.attnotnull ? '' : ' | null'}`).join('\n')}\n}\n\n`
  }
  output += 'type ReadTable<Row> = { Row: Row, Insert: never, Update: never, Relationships: [] }\n'
  output += 'export type ManualPaymentDatabase = { public: {\n  Tables: {\n'
  output += Object.entries(models).map(([table, model]) => `    ${table}: ReadTable<${model}>`).join('\n')
  output += '\n  }\n  Views: Record<string, never>\n  Enums: Record<string, never>\n  CompositeTypes: Record<string, never>\n  Functions: {\n'
  for (const name of ['prepare_manual_payment', 'cancel_manual_payment']) {
    const { rows } = await db.query(`select p.proargnames, array(select t.typname from unnest(p.proargtypes) with ordinality a(oid,n) join pg_type t on t.oid=a.oid order by a.n) types from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname=$1`, [name])
    const args = rows[0].proargnames.map((arg, i) => `${arg}: ${tsType(rows[0].types[i])}`).join(', ')
    output += `    ${name}: { Args: { ${args} }, Returns: ManualPaymentRequest }\n`
  }
  output += '  }\n} }\n'
  await writeFile('apps/ledger-suit/types/manual-payment.types.ts', output)
  console.log('Regenerated manual payment contract from PostgreSQL catalog.')
}

if (process.argv.includes('--generate-admin-contract')) {
  let output = '// Generated by scripts/test-manual-payment-embedded.mjs --generate-admin-contract.\n// Source: migrated PostgreSQL catalog. Do not edit.\nimport type { Json } from \'./database.types\'\n\n'
  output += 'export type PlatformAdminDatabase = { public: {\n  Tables: Record<string, never>\n  Views: Record<string, never>\n  Enums: Record<string, never>\n  CompositeTypes: Record<string, never>\n  Functions: {\n'
  for (const name of ['platform_admin_read', 'platform_admin_review_payment']) {
    const { rows } = await db.query(`select p.proargnames,p.pronargdefaults, array(select t.typname from unnest(p.proargtypes) with ordinality a(oid,n) join pg_type t on t.oid=a.oid order by a.n) types from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname=$1`, [name])
    const row = rows[0]
    const args = row.proargnames.map((arg, i) => `${arg}${i >= row.proargnames.length - row.pronargdefaults ? '?' : ''}: ${row.types[i] === 'int4' ? 'number' : 'string'}`).join(', ')
    output += `    ${name}: { Args: { ${args} }, Returns: Json }\n`
  }
  output += '  }\n} }\n'
  await writeFile('apps/ledger-suit/types/platform-admin.types.ts', output)
  console.log('Regenerated platform admin RPC contract from PostgreSQL catalog.')
}

