// pgTAP is unavailable in WASM. These assertion functions execute the same SQL
// suite and throw on any mismatch; they are not substitutes for live Storage.
await db.exec(`
create function extensions.plan(integer) returns text language sql as $$select 'begin assertions'::text$$;
create function extensions.no_plan() returns text language sql as $$select 'begin assertions'::text$$;
create function extensions.is(anyelement,anyelement,text) returns text language plpgsql as $$
begin if $1 is distinct from $2 then raise exception 'Assertion failed: % (actual %, expected %)', $3,$1,$2; end if; return $3; end;$$;
create function extensions.ok(boolean,text) returns text language plpgsql as $$
begin if $1 is distinct from true then raise exception 'Assertion failed: %',$2; end if; return $2; end;$$;
create function extensions.throws_ok(text,text,text,text) returns text language plpgsql as $$
declare caught boolean:=false; begin
  begin execute $1; exception when others then
    caught:=true;
    if sqlstate is distinct from $2 or ($3 is not null and sqlerrm is distinct from $3) then
      raise exception 'Assertion failed: % (actual % %, expected % %)', $4,sqlstate,sqlerrm,$2,$3;
    end if;
  end;
  if not caught then raise exception 'Assertion failed: % (no exception)', $4; end if;
  return $4;
end;$$;
create function extensions.finish() returns text language sql as $$select 'assertions passed'::text$$;
`)
for (const filename of ['77_manual_payment_test.sql', '24_plan_aware_paymob_checkout_test.sql', '78_platform_admin_test.sql']) {
  const suite = (await readFile(`apps/ledger-suit/supabase/tests/${filename}`, 'utf8'))
    .replace('create extension if not exists pgtap with schema extensions;', '')
  const results = await db.exec(suite)
  let assertions = 0
  for (const result of results) for (const row of result.rows ?? []) {
    if (row.is || row.ok || row.throws_ok) assertions++
  }
  console.log(`${filename}: ${assertions} SQL assertions passed.`)
}
