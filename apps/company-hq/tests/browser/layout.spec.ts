import { expect, test } from '@playwright/test'
import { canonicalRoleFallbacks, installWorkforceFixture, lessonId, taskId } from './workforce-fixture'

test('full roster distinguishes configured employees from actual individual connections', async ({ page }) => {
  const fixture = await installWorkforceFixture(page)
  await fixture.open()
  await expect(page.getByRole('region', { name: 'Interactive 3D workspace', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Team', exact: true }).click()
  const panel = page.getByRole('complementary', { name: 'Team', exact: true })
  await expect(page.getByRole('dialog', { name: 'Team', exact: true })).toHaveCount(0)
  await expect(panel.locator('.bs-hq-team__chief')).toContainText('Steve Fixture')
  await expect(panel.getByText('Fixture department', { exact: true })).toHaveCount(1)
  await panel.getByRole('tab', { name: 'People', exact: true }).click()
  await expect(panel.locator('.bs-hq-team__employee')).toHaveCount(10)
  for (const agent of fixture.snapshot().agents) await expect(panel.getByText(agent.name, { exact: true })).toHaveCount(1)
  await expect(panel.locator('.bs-hq-team__employee[aria-description$="Configured · not connected"]')).toHaveCount(9)
  await expect(panel.locator('.bs-hq-team__employee[aria-description$="CEO · Connected"]')).toHaveCount(1)
  await expect(page.locator('.bs-hologram-scene__agent-label[data-cosmetic="true"][data-activity="offline"]')).toHaveCount(9)
  await expect(page.getByText('Worker connected · Agents working: 0', { exact: true })).toBeVisible()
  await fixture.publish(canonicalRoleFallbacks(fixture.snapshot()))
  for (const role of ['HR Recruiter', 'HR Evaluator', 'Research & Market Intelligence Lead', 'Customer Acquisition & Partnerships Lead', 'Customer Success & Onboarding Lead', 'Social & Community Lead', 'Email & Lifecycle Lead', 'Development & Maintenance Lead']) await expect(panel.getByText(role, { exact: true })).toHaveCount(1)
  await panel.getByRole('tab', { name: 'Departments', exact: true }).click()
  await expect(panel.getByText('HR & Agent Development', { exact: true })).toHaveCount(1)
  await expect(panel.getByText('hr-agent-development', { exact: true })).toHaveCount(0)
  await fixture.publish({ ...fixture.snapshot(), agents: fixture.snapshot().agents.map(agent => agent.id === 'AG-DEV-001' ? { ...agent, role: 'Fixture specialist', departmentKey: 'unmapped-fixture-department' } : agent) })
  await expect(panel.getByText('unmapped-fixture-department', { exact: true })).toHaveCount(1)
  await panel.getByRole('tab', { name: 'People', exact: true }).click()
  await expect(panel.getByText('Fixture specialist', { exact: true })).toHaveCount(1)
  const employee = panel.getByRole('button', { name: /Agent details: Fixture employee 2/ })
  await employee.click()
  const employeeDetails = page.getByRole('complementary', { name: 'Fixture employee 2', exact: true })
  await expect(employeeDetails.getByRole('region', { name: 'Office metrics', exact: true })).toBeVisible()
  await employeeDetails.getByRole('heading', { name: 'Fixture employee 2', exact: true }).press('Escape')
  await expect(employee).toBeFocused()
  await panel.getByRole('button', { name: 'Close', exact: true }).click()
  const reads = fixture.requests.filter(request => request === 'GET /api/hq/agents').length
  await page.waitForTimeout(1200)
  expect(fixture.requests.filter(request => request === 'GET /api/hq/agents')).toHaveLength(reads)
  await page.getByRole('combobox', { name: 'Workplaces', exact: true }).click()
  await page.getByRole('option', { name: 'Fixture department', exact: true }).click()
  const office = page.getByRole('complementary', { name: 'Fixture department', exact: true })
  await expect(office.getByRole('region', { name: 'Office metrics', exact: true })).toBeVisible()
  for (const agent of fixture.snapshot().agents.slice(1)) await expect(office.getByText(agent.name, { exact: true })).toHaveCount(1)
  await expect(office.getByText('Offline', { exact: true })).toHaveCount(9)
  await fixture.publish({ ...fixture.snapshot(), runtime: { connected: false, lastSeenAt: null } })
  await expect(page.getByText('No agents connected', { exact: true })).toBeVisible()
  await expect(page.locator('.bs-hologram-scene__agent-label[data-cosmetic="true"]')).toHaveCount(0)
  expect(fixture.unexpected).toEqual([])
  expect(fixture.errors).toEqual([])
})

test('Chat starts work while Tasks shows event-driven review and published learning', async ({ page }) => {
  const fixture = await installWorkforceFixture(page)
  await fixture.open()
  await page.getByRole('button', { name: 'Tasks', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'Tasks', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Leave selected workplace:/ })).toHaveCount(0)
  const panel = page.locator('.bs-hq-workforce')
  await expect(panel.getByRole('tab', { name: /^All/ })).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Create task', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Chat', exact: true }).click()
  const composer = page.getByLabel('Message Steve', { exact: false })
  const prompt = 'Ask HR to prepare a bounded draft with source receipts and a clear recommendation.'
  await composer.fill(prompt)
  await composer.press('Enter')
  await expect(page.getByRole('log', { name: 'Company conversation' })).toContainText(prompt)
  expect(fixture.chatRequests[0]?.prompt).toBe(prompt)
  expect(fixture.taskRequests).toHaveLength(0)
  await composer.press('Escape')
  await page.getByRole('button', { name: 'Tasks', exact: true }).click()
  const now = new Date().toISOString()
  const snapshot = { ...fixture.snapshot(), tasks: [{
    id: taskId, title: 'Fixture task', brief: prompt, acceptance: 'Include source receipts.',
    assigneeId: 'AG-HR-001', status: 'queued' as const, createdAt: now, updatedAt: now,
    completedAt: null, repairCount: 0, deliverable: null, reviewSummary: null, error: null,
  }] }
  await fixture.publish(snapshot)
  await panel.getByRole('button', { name: /Fixture task/ }).click()
  const taskDetails = page.getByRole('complementary', { name: 'Fixture task', exact: true })
  await expect(taskDetails.getByText('No deliverable has been submitted yet.')).toBeVisible()
  await fixture.publish({ ...snapshot, tasks: snapshot.tasks!.map(task => ({ ...task, status: 'completed', completedAt: now, updatedAt: now, deliverable: 'Reviewed fixture draft <img src=x onerror="window.untrustedRan=true">', reviewSummary: 'Acceptance criteria verified against the submitted draft.' })), lessons: [{ id: lessonId, sourceType: 'task', sourceId: taskId, status: 'published', summary: 'Source receipts improve review', body: 'Keep <script>window.untrustedRan=true</script> as escaped source text.', agentId: 'AG-HR-001', createdAt: now, reviewedAt: now, publishedAt: now, publicationReference: 'https://drive.google.com/file/d/fixture_receipt/view' }] })
  await expect(taskDetails.getByText('Completed', { exact: true }).first()).toBeVisible()
  await expect(taskDetails.getByRole('button', { name: 'Review next task', exact: true })).toHaveCount(0)
  await expect(taskDetails.getByText('Acceptance criteria verified against the submitted draft.', { exact: true })).toBeVisible()
  await expect(taskDetails.getByText('Reviewed fixture draft <img src=x onerror="window.untrustedRan=true">', { exact: true })).toBeVisible()
  await expect(taskDetails.locator('img')).toHaveCount(0)
  await page.getByRole('button', { name: 'Open Company Brain', exact: true }).click()
  const brain = page.getByRole('complementary', { name: 'Company Brain', exact: true })
  await brain.getByRole('tab', { name: 'Learning', exact: true }).click()
  const learning = brain.getByRole('tabpanel', { name: 'Learning', exact: true })
  await learning.getByRole('button', { name: 'Source receipts improve review', exact: true }).click()
  const lesson = page.getByRole('complementary', { name: 'Source receipts improve review', exact: true })
  await expect(lesson.getByText('Keep <script>window.untrustedRan=true</script> as escaped source text.', { exact: true })).toBeVisible()
  await expect(lesson.getByRole('link', { name: 'Open Brain receipt' })).toHaveAttribute('href', 'https://drive.google.com/file/d/fixture_receipt/view')
  expect(await page.evaluate(() => (window as unknown as { untrustedRan?: boolean }).untrustedRan)).toBeUndefined()
  expect(fixture.unexpected).toEqual([])
  expect(fixture.errors).toEqual([])
})

test('chat keyboard submission stays available alongside the workforce tabs', async ({ page }) => {
  const fixture = await installWorkforceFixture(page)
  await fixture.open()
  await page.getByRole('button', { name: 'Chat', exact: true }).click()
  const composer = page.getByLabel('Message Steve', { exact: false })
  await expect(composer).toBeEnabled()
  await composer.fill('First fixture line')
  await composer.press('Shift+Enter')
  await composer.pressSequentially('Second fixture line')
  expect(fixture.chatRequests).toHaveLength(0)
  await composer.press('Enter')
  await expect(page.getByRole('log', { name: 'Company conversation' })).toContainText('First fixture line\nSecond fixture line')
  await expect(composer).toHaveValue('')
  expect(fixture.chatRequests).toHaveLength(1)
  expect(fixture.chatRequests[0]?.prompt).toBe('First fixture line\nSecond fixture line')
})

