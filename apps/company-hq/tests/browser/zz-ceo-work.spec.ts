import { test, expect, type Page } from '@playwright/test'

const origin = 'http://127.0.0.1:4337'
const keys = ['AG-CEO-001', 'AG-HR-001', 'AG-HR-002', 'AG-HR-003', 'playbook', 'bootstrap', 'charter', 'workingAgreement', 'registry', 'organization', 'hrCharter', 'workforceSkill', 'home', 'soul', 'milestones', 'mode']
const files = Object.fromEntries(keys.map(key => [key, 'synthetic-browser-' + key]))
async function state(page: Page) { return (await (await page.request.get('/api/hq/state')).json()).state }

// Runs after the existing no-worker acceptance tests. Only the test-server CLI fixture
// recognizes this exact marker + file scope; production has no synthetic-worker hook.
test('synthetic local dispatcher: original CEO message, explicit proposal and approval, exact Brain scope, four roles and one durable reply', async ({ page }) => {
  test.setTimeout(60_000)
  const errors: string[] = [], externalRequests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (new URL(request.url()).origin !== origin) externalRequests.push(request.url()) })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/auth/login')
  await page.getByRole('textbox', { name: 'Password', exact: true }).fill('synthetic-browser-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sign out', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Talk to CEO', exact: true }).click()
  const title = 'Synthetic CEO end-to-end ' + crypto.randomUUID().slice(0, 8)
  const original = title + ': private founder context stays with Steve.'
  await page.getByLabel('Message to CEO').fill(original)
  await page.getByRole('button', { name: 'Send to CEO', exact: true }).click()
  const initial = await state(page), message = initial.messages.find((item: { text: string }) => item.text === original)
  expect(message.status).toBe('queued')
  expect(initial.messages.some((item: { replyTo?: string }) => item.replyTo === message.id)).toBe(false)
  const article = page.locator(`[data-message-id="${message.id}"]`)
  await article.getByRole('button', { name: 'Plan work from this message', exact: true }).click()
  await expect(page.locator(`[data-source-message-id="${message.id}"]`)).toContainText(original)
  await expect(page.getByLabel('Outcome and relevant inputs')).toHaveValue('')
  await expect(page.getByRole('dialog', { name: 'Propose a CEO assignment', exact: true })).toContainText('Your original conversation stays with Steve')
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill(title)
  await page.getByLabel('Outcome and relevant inputs').fill('Synthetic browser assignment shared with HR, excluding the private conversation.')
  await page.getByLabel('Deliverable and definition of done').fill('Noah evidence, independent Iris review, Maya consolidation and one Steve reply.')
  await page.getByLabel('Allowed actions and stop conditions').fill('Exact read-only synthetic Brain fixtures. No external calls, writes, public tools or spending.')

  // The server commits, but the first response is lost. Retry must use the same receipt.
  const proposalKeys: string[] = []
  await page.route('**/api/hq/action', async route => {
    const body = route.request().postDataJSON()
    if (body.action !== 'create_task') return route.continue()
    proposalKeys.push(body.idempotencyKey)
    const saved = await route.fetch(); expect(saved.ok()).toBe(true)
    await route.abort('failed')
  })
  await page.getByRole('button', { name: 'Save proposal', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Your draft is preserved')
  await expect(page.getByRole('textbox', { name: 'Title', exact: true })).toHaveValue(title)
  await expect(page.locator(`[data-source-message-id="${message.id}"]`)).toContainText(original)
  await page.unroute('**/api/hq/action')
  await page.route('**/api/hq/action', route => {
    const body = route.request().postDataJSON()
    if (body.action === 'create_task') proposalKeys.push(body.idempotencyKey)
    return route.continue()
  })
  await page.getByRole('button', { name: 'Save proposal', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.unroute('**/api/hq/action')
  expect(proposalKeys).toHaveLength(2); expect(proposalKeys[0]).toBe(proposalKeys[1])
  const proposed = await state(page)
  const linked = proposed.tasks.filter((item: { sourceMessage?: { id: string } }) => item.sourceMessage?.id === message.id)
  expect(linked).toHaveLength(1)
  const taskId = linked[0].id
  expect(linked[0]).toMatchObject({ status: 'proposed', approvedAt: null, sourceMessage: { id: message.id, text: original } })
  expect(linked[0].sourceMessage.digest).toMatch(/^[a-f0-9]{64}$/)
  expect(linked[0].workflow).toBeUndefined()
  expect(proposed.workflowRuns.filter((run: { taskId: string }) => run.taskId === taskId)).toEqual([])
  const scope = { action: 'authorize_workflow', id: taskId, brainFiles: files, daily: false, timezoneConfirmed: false, allowedTools: [], publicInputs: [] }
  expect((await page.request.post('/api/hq/action', { headers: { Origin: origin }, data: { ...scope, idempotencyKey: crypto.randomUUID() } })).status()).toBe(409)
  await page.getByRole('button', { name: 'Tasks', exact: true }).click()
  await page.getByRole('button', { name: new RegExp(title) }).click()
  const detail = page.getByRole('dialog', { name: title, exact: true })
  await expect(detail.getByRole('button', { name: 'Authorize Brain work', exact: true })).toHaveCount(0)
  await detail.getByRole('button', { name: 'Approve this plan', exact: true }).click()
  await expect(detail).toContainText('Approved · queued')
  const approved = await state(page)
  expect(approved.workflowRuns.filter((run: { taskId: string }) => run.taskId === taskId)).toEqual([])
  expect(approved.messages.find((item: { id: string }) => item.id === message.id).status).toBe('queued')
  await detail.getByRole('button', { name: 'Authorize Brain work', exact: true }).click()
  const workflow = page.getByRole('dialog', { name: 'Approve the Brain files for this task', exact: true })
  await expect(workflow.locator(`[data-workflow-task-id="${taskId}"]`)).toBeVisible()
  await expect(workflow).toContainText('No public browsing, Brain changes, spending or daily schedule')
  await expect(workflow).toContainText('Execution still requires an approved host')
  await expect(workflow.getByRole('textbox')).toHaveCount(16)
  await expect(workflow.getByRole('button', { name: 'Authorize read-only work', exact: true })).toBeDisabled()
  for (const key of keys) await workflow.locator(`input[name="${key}"]`).fill(`https://drive.google.com/file/d/${files[key]}/view`)
  // Duplicate references are rejected locally without losing the selected scope.
  await workflow.locator('input[name="AG-HR-001"]').fill(files['AG-CEO-001']!)
  await workflow.getByRole('button', { name: 'Authorize read-only work', exact: true }).click()
  await expect(workflow.getByRole('alert')).toContainText('Choose 16 distinct valid Drive/Docs files')
  expect((await state(page)).tasks.find((item: { id: string }) => item.id === taskId).workflow).toBeUndefined()
  await workflow.locator('input[name="AG-HR-001"]').fill(`https://docs.google.com/document/d/${files['AG-HR-001']}/edit`)

  const scopeKeys: string[] = []
  await page.route('**/api/hq/action', route => {
    const body = route.request().postDataJSON()
    if (body.action !== 'authorize_workflow') return route.continue()
    scopeKeys.push(body.idempotencyKey)
    return route.abort('failed')
  })
  await workflow.getByRole('button', { name: 'Authorize read-only work', exact: true }).click()
  await expect(workflow.getByRole('alert')).toContainText('Your draft is preserved')
  await expect(workflow.locator('input[name="AG-HR-001"]')).toHaveValue(`https://docs.google.com/document/d/${files['AG-HR-001']}/edit`)
  expect((await state(page)).workflowRuns.filter((run: { taskId: string }) => run.taskId === taskId)).toEqual([])
  await page.unroute('**/api/hq/action')
  await page.route('**/api/hq/action', async route => {
    const body = route.request().postDataJSON()
    if (body.action === 'authorize_workflow') {
      scopeKeys.push(body.idempotencyKey)
      expect(body.brainFiles).toEqual(files)
      expect(body.allowedTools).toEqual([]); expect(body.publicInputs).toEqual([])
      expect(body.daily).toBe(false); expect(body.timezoneConfirmed).toBe(false)
      // An ambiguous response must reconcile from authenticated persisted state.
      // SSE readback closes this exact saved scope, without dispatching it twice.
      const saved = await route.fetch(); expect(saved.ok()).toBe(true)
      return route.abort('failed')
    }
    return route.continue()
  })
  await workflow.getByRole('button', { name: 'Authorize read-only work', exact: true }).click()
  await expect(workflow).toHaveCount(0)
  await page.unroute('**/api/hq/action')
  expect(scopeKeys).toHaveLength(2); expect(scopeKeys[0]).toBe(scopeKeys[1])
  await expect.poll(async () => (await state(page)).tasks.find((item: { id: string }) => item.id === taskId).status, { timeout: 15_000 }).toBe('completed')
  const completed = await state(page), runs = completed.workflowRuns.filter((run: { taskId: string }) => run.taskId === taskId)
  expect(runs).toHaveLength(1)
  expect(runs[0]).toMatchObject({ status: 'completed', stages: ['research', 'evaluate', 'consolidate', 'reply'], delivery: 'delivered', failures: [] })
  expect(completed.brain.events.filter((event: { taskId: string }) => event.taskId === taskId).map((event: { agentId: string }) => event.agentId).sort()).toEqual(['AG-CEO-001', 'AG-HR-001', 'AG-HR-002', 'AG-HR-003'])
  expect(completed.runtime.enabled).toBe(false)
  const replies = completed.messages.filter((item: { replyTo?: string }) => item.replyTo === message.id)
  expect(replies).toHaveLength(1)
  expect(replies[0]).toMatchObject({ role: 'ceo', taskId })
  expect(replies[0].text).toContain('Synthetic browser verification complete')
  expect(completed.messages.find((item: { id: string }) => item.id === message.id).status).toBe('answered')
  await page.reload()
  await expect(page.locator('.bs-living-office')).toHaveAttribute('data-renderer', 'webgl', { timeout: 20_000 })
  await page.getByRole('button', { name: 'Talk to CEO', exact: true }).click()
  await expect(page.locator(`[data-message-id="${message.id}"]`)).toContainText('Answered')
  await expect(page.locator(`[data-message-id="${message.id}"]`).getByRole('button', { name: 'Plan work from this message', exact: true })).toHaveCount(0)
  await expect(page.locator(`[data-message-id="${replies[0].id}"]`)).toContainText('No live model or Drive request was made')
  await expect(page.getByRole('dialog')).toContainText('Live execution unavailable')
  await page.locator(`[data-message-id="${replies[0].id}"]`).scrollIntoViewIfNeeded()
  await expect(page.locator(`[data-message-id="${replies[0].id}"]`)).toBeVisible()
  await page.screenshot({ path: 'test-results/ceo-synthetic-durable-reply.png', fullPage: true })
  expect((await state(page)).messages.filter((item: { replyTo?: string }) => item.replyTo === message.id)).toHaveLength(1)
  expect(externalRequests).toEqual([]); expect(errors).toEqual([])
})
